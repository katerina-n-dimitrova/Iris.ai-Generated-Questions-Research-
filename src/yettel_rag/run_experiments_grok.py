#!/usr/bin/env python3
"""Generate Yettel enrichment questions with Grok and rerun the four retrieval arms.

The gpt-5.4-mini evaluation queries and the original enrichment cache are left
untouched. Chunk and query embeddings are reused because those texts do not
change; only Grok-generated questions are newly embedded.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "src" / "yettel_rag"))
sys.path.insert(0, str(ROOT / "src" / "mhrag_vectoronly"))

import config  # noqa: E402
import run_experiments as E  # noqa: E402

GPT_RENDER = E.render
GPT_DATA = ROOT / "data" / "processed" / "yettel_bg_experiments"
GPT_RESULTS = ROOT / "results" / "yettel_bg_experiments"
DATA = ROOT / "data" / "processed" / "yettel_bg_experiments_grok"
RESULTS = ROOT / "results" / "yettel_bg_experiments_grok"
REPORT = ROOT / "report" / "yettel_bg_adaptive_questions_grok.html"
JSON_FENCE = re.compile(r"^```(?:json)?\s*|\s*```$", re.IGNORECASE)


def parse_json_content(text: str) -> dict:
    raw = JSON_FENCE.sub("", (text or "").strip())
    return json.loads(raw)


def grok_call_json(system: str, user: str, seed: int = E.A.SEED) -> dict:
    client = config.get_xai_client()
    last_error = None
    for attempt in range(6):
        try:
            response = client.chat.completions.create(
                model=config.XAI_CHAT_MODEL,
                temperature=0.3,
                max_tokens=4096,
                response_format={"type": "json_object"},
                messages=[
                    {"role": "system", "content": system},
                    {"role": "user", "content": user},
                ],
                extra_body={"reasoning": {"effort": "low"}},
            )
            content = response.choices[0].message.content
            if not content:
                raise RuntimeError("Grok returned empty message content")
            return parse_json_content(content)
        except Exception as error:
            last_error = error
            wait = min(32, 2**attempt)
            print(f"[grok-retry] {error} sleep={wait}s", flush=True)
            time.sleep(wait)
    raise last_error


def rebind_paths() -> None:
    for directory in (DATA, RESULTS, REPORT.parent):
        directory.mkdir(parents=True, exist_ok=True)
    E.DATA = DATA
    E.RESULTS = RESULTS
    E.REPORT = REPORT
    E.A.DATA = DATA
    E.A.RESULTS = RESULTS
    E.A.REPORT = REPORT
    E.A.CHUNKS_PATH = DATA / "chunks.jsonl"
    E.A.QUERIES_PATH = DATA / "queries.jsonl"
    E.A.SUMMARY_PATH = DATA / "summary.json"
    E.A.GEN_PATH = DATA / "adaptive_generations.jsonl"
    E.A.CHUNK_VECTORS = RESULTS / "chunk_vectors.json"
    E.A.QUERY_VECTORS = RESULTS / "query_vectors.json"
    E.A.BOUNDED_VECTORS = RESULTS / "bounded_question_vectors.json"
    E.A.UNBOUNDED_VECTORS = RESULTS / "unbounded_question_vectors.json"
    E.A.METRICS = RESULTS / "metrics.json"
    E.A.RANKINGS = RESULTS / "rankings.json"
    E.A.MAX_WORKERS = 8
    E.A.MAX_RETRIES = 6
    E.A.MODEL = config.XAI_CHAT_MODEL
    E.C.DATA = DATA
    E.C.RESULTS = RESULTS
    E.C.REPORT = REPORT
    E.C.ARTICLE_GENERATIONS = DATA / "article_question_generations.jsonl"
    E.C.ARTICLE_VECTORS = RESULTS / "article_question_vectors.json"
    E.C.ARTICLE_RANKINGS = RESULTS / "article_chunk_question_rankings.jsonl"
    E.C.MAX_WORKERS = 8
    E.C._call_json_once = grok_call_json
    E.A.call_json = E.C.call_json_resilient


def copy_shared_artifacts() -> None:
    for name in ("chunks.jsonl", "queries.jsonl", "summary.json"):
        source = GPT_DATA / name
        dest = DATA / name
        if not dest.exists():
            shutil.copy2(source, dest)
    for name in ("chunk_vectors.json", "query_vectors.json"):
        source = GPT_RESULTS / name
        dest = RESULTS / name
        if not dest.exists():
            shutil.copy2(source, dest)


def grok_render(payload: dict) -> None:
    GPT_RENDER(payload)
    html = REPORT.read_text(encoding="utf-8")
    html = html.replace(
        "Both were generated by gpt-5.4-mini, however, which can introduce same-model stylistic coupling; these results should therefore be described as a controlled same-model synthetic benchmark.",
        "Evaluation queries remain gpt-5.4-mini. Adaptive enrichment questions in this table were generated by grok-4.6 with the same prompts, budgets, and retrieval protocol, so this run is the cross-model control for same-generator bias.",
    )
    html = html.replace(
        "340-document Yettel Bulgaria RAG — baseline and adaptive generated questions",
        "340-document Yettel Bulgaria RAG — grok-4.6 enrichment questions",
    )
    REPORT.write_text(html, encoding="utf-8")


def run() -> dict:
    rebind_paths()
    copy_shared_artifacts()
    print(
        f"[grok] model={config.XAI_CHAT_MODEL} chunks={E.A.CHUNKS_PATH} "
        f"gen={E.A.GEN_PATH}",
        flush=True,
    )
    E.render = grok_render
    return E.run()


if __name__ == "__main__":
    run()
